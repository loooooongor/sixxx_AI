def normalize_mode(mode: str | None) -> str:
    """把前端或 API 的詳略參數正規化為 detailed / concise。"""
    value = str(mode or "").strip().lower()
    if value in ("detailed", "full", "詳細", "详细"):
        return "detailed"
    return "concise"


