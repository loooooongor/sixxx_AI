@dataclass
class PromptBundle:
    """一次解卦的完整 prompt。"""

    system: str
    user: str

    def messages(self) -> list[dict]:
        return [{"role": "user", "content": self.user}]


def build_prompt(board: dict, question: str,
                 extra_history: list[dict] | None = None) -> PromptBundle:
    """組出解卦 prompt。

    Args:
        board: ``build_cast()`` 產出的卦盤 dict。
        question: 使用者的占問。
        extra_history: 追問時帶入的先前對話（user/assistant 交替）。
    """
    import json

    kb = get_kb()
    context = kb.build_context(board, question)

    system = SYSTEM_TEMPLATE.format(knowledge=context)
    board_text = board_to_prompt_text(board)
    board_json = json.dumps(_compact_for_prompt(board), ensure_ascii=False, indent=1)

    user = USER_TEMPLATE.format(
        question=question,
        board_text=board_text,
        board_json=board_json,
    )

    if extra_history:
        convo = "\n\n".join(
            f"### {'使用者' if m['role'] == 'user' else '占卜師'}\n{m['content']}"
            for m in extra_history[-6:]
        )
        user += f"\n\n## 先前對話（供延續，勿重複整段）\n\n{convo}\n"

    return PromptBundle(system=system, user=user)


def _compact_for_prompt(board: dict) -> dict:
    """精簡 JSON：去掉前端才需要的欄位，保留推理所需的全部資訊。"""
    keys = [
        "cast_time", "hexagram", "changed_hexagram", "palace", "palace_wx",
        "world_pos", "response_pos", "month_zhi", "month_wx", "day_gz", "day_wx",
        "xunkong", "yongshen_qin", "yongshen_lines", "moving_positions",
        "moving_text", "gua_bian", "fu_yin", "fan_yin", "sanhe",
        "is_liuhe_gua", "is_liuchong_gua", "changed_is_liuhe", "changed_is_liuchong",
        "gua_ci", "changed_gua_ci", "yongshen_reason",
    ]
    out = {k: board.get(k) for k in keys}
    # 只保留實成之局；虛合／缺支不進 prompt，避免模型把它當成已成立的局來寫。
    out["sanhe"] = {
        ju: info for ju, info in (board.get("sanhe") or {}).items()
        if str(info.get("status", "")).startswith("實成")
    }
    out["lines"] = [
        {k: ln.get(k) for k in (
            "pos_name", "yao_name", "shen", "qin", "gan", "zhi", "wx",
            "yin_yang", "state", "stage", "tags", "jin_tui",
            "change_gan", "change_zhi", "change_qin", "role",
            "effective", "effective_reason",
        )}
        for ln in board.get("lines", [])
    ]
    moving_ci = {}
    for pos in board.get("moving_positions", []):
        ln = next((l for l in board.get("lines", []) if l["pos"] == pos), None)
        if ln:
            key = ln["yao_name"]
            ci = (board.get("yao_ci") or {}).get(key)
            if ci:
                moving_ci[key] = ci
    out["moving_yao_ci"] = moving_ci
    return out


#: 追問時使用的輕量 prompt（不重送整份知識庫）
FOLLOWUP_SYSTEM = """你是一位精研六爻十年的占卜師，正在延續先前的一次解卦，以繁體中文回答使用者的追問。

規則：
1. 仍以先前的卦盤為唯一事實，不得改算卦盤。
2. 只回答被問到的部分，不要重複整段解卦；需要時引用卦盤中具體的爻與象作為依據。
3. 若追問超出卦象能回答的範圍（例如要你預測具體金額、日期、人名），坦誠說明卦只能定勢與時機，
   不可編造具體事實。
4. 保持先前解卦的結論與用語一致；若追問揭露了新資訊而使判斷需要修正，明確說明修正了什麼、為什麼。
5. 繁體中文，語氣沉穩，長度以講清楚為準。
"""


def build_followup(board: dict, question: str, prior_answer: str,
                   followup: str) -> PromptBundle:
    """組出追問 prompt（帶上原始卦盤與前一次解卦）。"""
    from .divination import board_to_prompt_text

    board_text = board_to_prompt_text(board)
    user = (
        f"## 原始占問\n\n{question}\n\n"
        f"## 卦盤（引擎計算，不可更動）\n\n```\n{board_text}\n```\n\n"
        f"## 先前的解卦內容\n\n{prior_answer}\n\n"
        f"## 使用者的追問\n\n{followup}\n"
    )
    return PromptBundle(system=FOLLOWUP_SYSTEM, user=user)
